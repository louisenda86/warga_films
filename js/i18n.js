let lang = 'ms';
// Bahasa Melayu first, as on the channel; the choice is remembered once a visitor switches.
try { lang = localStorage.getItem('wf-lang') === 'en' ? 'en' : 'ms'; } catch (e) { /* storage blocked */ }

const listeners = new Set();
export const getLang = () => lang;
export function setLang(l) {
  if (l !== 'ms' && l !== 'en') return;
  lang = l;
  document.documentElement.lang = l === 'ms' ? 'ms' : 'en';
  try { localStorage.setItem('wf-lang', l); } catch (e) { /* storage blocked */ }
  for (const fn of listeners) fn(l);
}
export const onLang = (fn) => { listeners.add(fn); return () => listeners.delete(fn); };
/** Interface string by key. */
export const t = (key) => (UI[key] ? UI[key][lang] : key);
/** Pick the current language from a {ms, en} object. */
export const L = (o) => (o && typeof o === 'object' && 'ms' in o ? o[lang] : o);
